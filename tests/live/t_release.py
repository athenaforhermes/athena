#!/usr/bin/env python3
"""The promises this plugin makes about itself, checked against the files that make them.

`hermes plugins validate` is the catalogue's admission gate and it is the *runtime*
truth: it loads the plugin and compares what actually registered against the
manifest. It was silently broken for a whole version — a tool registered but not
declared — and nothing here noticed, because a plugin that works perfectly and a
manifest that lies look identical from inside the suite.

This file is the other half: the repository's own promises, checked without Hermes.
The version in three files, the tool surface in three shapes, the release files, the
third-party inventory a licence audit depends on, the Hermes window the plugin says
it needs. Every one of these has been true by accident at some point, which is the
only reason a check is worth writing: a promise nothing executes is a promise that
breaks in somebody else's checkout.

Deliberately *not* a byte-for-byte regeneration of `THIRD-PARTY.md`. That file is a
walk of `engine/node_modules` wrapped in prose a person wrote, and a file that has to
be regenerated byte-exactly cannot carry prose. So the walk is re-run here and every
claim the file makes is checked against it — the package count, the licence table,
the full list and its order, the one package with no licence field, the example
directories left out — plus the claim that every one of them is permissive, which is
the sentence a licence audit actually rests on.

Usage: env -u PYTHONPATH <venv python> t_release.py            (from this directory)
       ... t_release.py --dump-third-party                     to print the walk
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

# The plugin *is* the repository this file lives in: `tests/live/` is three levels
# below it. Derived rather than configured, because a release check that can be
# pointed at another directory is a release check that can pass about somewhere else.
PLUGIN = Path(__file__).resolve().parents[2]

PASS = FAIL = 0
FAILURES: List[str] = []
SKIPPED: List[str] = []

# Anything a shipped file may not exceed. Not a style rule — a ratchet: both of these
# are being split in the 1.0 work, and a cap is what stops the split from quietly
# undoing itself. Lower them as the splits land; never raise one without saying why.
SIZE_CAPS = {
    "dashboard/plugin_api.py": 8500,     # 8,291 after the capability runner came out; 9,240 when this was written
    "desktop/plugin.js": 9600,           # 9,105
}
ANY_FILE_CAP = 10000

# Copyleft in a redistributed engine is a licence question, not a preference: this
# plugin ships `engine/node_modules` whole. LGPL is deliberately absent from this
# list (it is a linking question), and the packages with no licence field are named
# in THIRD-PARTY.md rather than assumed permissive.
COPYLEFT = ("GPL", "AGPL", "SSPL", "BUSL", "CPAL", "OSL", "EUPL", "CC-BY-NC")

SHIPPED_SUFFIXES = {".py", ".js", ".mjs", ".sh", ".yaml", ".yml", ".md", ".json", ".cmd", ".css"}
SKIP_DIRS = {"node_modules", "__pycache__", ".git", "tests-scratch"}


def check(name: str, ok: bool, detail: str = "") -> bool:
    global PASS, FAIL
    if ok:
        PASS += 1
        print(f"  ok   {name}")
    else:
        FAIL += 1
        FAILURES.append(name)
        print(f"  FAIL {name}" + (f"  -- {detail}" if detail else ""))
    return ok


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8", errors="replace")


# ----------------------------------------------------------------------------- versions

def yaml_scalar(text: str, key: str) -> Optional[str]:
    """A top-level `key: value` out of a YAML file, quotes stripped.

    Not a YAML parse: these two files are read for four scalars each, and a release
    check that needs a dependency to run is a release check that fails for the wrong
    reason on a machine that has not installed one.
    """
    m = re.search(rf"^{re.escape(key)}:\s*(.+?)\s*$", text, re.M)
    if not m:
        return None
    return m.group(1).strip().strip('"').strip("'")


def yaml_list(text: str, key: str, indent: int = 2) -> List[str]:
    """The `- item` lines under `key:` at the given indentation."""
    out: List[str] = []
    m = re.search(rf"^{re.escape(key)}:\s*$", text, re.M)
    if not m:
        return out
    pad = " " * indent
    for line in text[m.end():].splitlines():
        if line.strip() and not line.startswith(pad):
            break
        if line.strip().startswith("- "):
            out.append(line.strip()[2:].strip().strip('"').strip("'"))
    return out


def parse_version(v: str) -> Tuple[int, ...]:
    parts = re.findall(r"\d+", v or "")
    return tuple(int(p) for p in parts[:3]) or (0,)


def satisfies(version: str, spec: str) -> bool:
    """`>=a.b.c,<d.e.f` — the two shapes this manifest has ever used."""
    have = parse_version(version)
    clauses = [c.strip() for c in (spec or "").split(",") if c.strip()]
    if not clauses:
        return True
    for c in clauses:
        m = re.match(r"^(>=|<=|>|<|==|=|~=|\^)?\s*v?([\d.]+)", c)
        if not m:
            return True                     # an operator this checker does not know: not its call
        op, want = m.group(1) or "==", parse_version(m.group(2))
        want = want + (0,) * (3 - len(want))
        cmp = have[:3]
        if op == ">=" and not cmp >= want: return False
        if op == "<=" and not cmp <= want: return False
        if op == ">" and not cmp > want: return False
        if op == "<" and not cmp < want: return False
        if op in ("==", "=") and not cmp == want: return False
        if op == "^" and not (want[0] == cmp[0] and cmp >= want): return False
        if op == "~=" and not (cmp[:2] == want[:2] and cmp >= want): return False
    return True


def installed_hermes_version() -> Optional[str]:
    """The Hermes this checkout is running on, if there is one to ask."""
    for cmd in (["hermes", "--version"],):
        try:
            out = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
        except (OSError, subprocess.SubprocessError):
            continue
        m = re.search(r"v(\d+\.\d+\.\d+)", out.stdout or "")
        if m:
            return m.group(1)
    return None


def check_versions() -> None:
    print("\nversions agree wherever they are written down")
    plug = read(PLUGIN / "plugin.yaml")
    pv = yaml_scalar(plug, "version")
    check("plugin.yaml declares a version", bool(pv and re.match(r"^\d+\.\d+\.\d+$", pv or "")),
          f"version={pv!r}")
    if not pv:
        return

    cat_path = PLUGIN / "docs" / "catalog-entry.yaml"
    cv = yaml_scalar(read(cat_path), "version") if cat_path.is_file() else None
    check("the catalogue entry carries the same version", cv == pv,
          f"catalog-entry={cv!r} plugin.yaml={pv!r}")

    changelog = PLUGIN / "CHANGELOG.md"
    if changelog.is_file():
        heads = re.findall(r"^##\s*\[?v?(\d+\.\d+\.\d+)", read(changelog), re.M)
        check("CHANGELOG's newest entry is this version", heads[:1] == [pv],
              f"changelog={heads[:1]} plugin.yaml={pv!r}")
    else:
        SKIPPED.append("CHANGELOG.md does not exist yet (added with the repo)")

    # The README may name a version in prose. If it does, it has to be this one.
    mentions = set(re.findall(r"\bv?(\d+\.\d+\.\d+)\b", read(PLUGIN / "README.md")))
    ours = {m for m in mentions if m.startswith(pv.rsplit(".", 1)[0])}
    check("no stale version in the README", not (ours - {pv}),
          f"README says {sorted(ours)}")


# ----------------------------------------------------------------------------- tools

def schemas_map(text: str) -> Dict[str, str]:
    """`SCHEMAS` short key -> registered tool name, out of the plugin's own source."""
    body = text[text.index("SCHEMAS"):text.index("def register(")] if "def register(" in text else text
    return {k: v for k, v in re.findall(r'"([a-z_]+)":\s*_schema\(\s*\n?\s*"([a-z0-9_]+)"', body)}


def registered_keys(text: str) -> List[str]:
    body = text[text.index("def register("):]
    return re.findall(r'_tool\("([a-z_]+)"', body)


def check_tools() -> None:
    print("\nthe tool surface is one surface, listed three ways")
    init = read(PLUGIN / "__init__.py")
    declared = yaml_list(read(PLUGIN / "plugin.yaml"), "provides_tools")
    smap = schemas_map(init)
    registered = registered_keys(init)
    names = {smap[k] for k in registered if k in smap}

    check("the manifest declares tools", len(declared) > 0, "provides_tools is empty")
    check("every registered tool has a schema", set(registered) <= set(smap),
          f"registered without a schema: {sorted(set(registered) - set(smap))}")
    check("every schema is registered", set(smap) <= set(registered),
          f"schemas never registered: {sorted(set(smap) - set(registered))}")
    check("the manifest lists exactly the registered tools",
          set(declared) == names,
          f"only in manifest: {sorted(set(declared) - names)}; "
          f"only in code: {sorted(names - set(declared))}")
    check("every tool name is athena_<key>",
          all(smap[k].replace("athena_", "", 1) in (k, k.replace("_", "")) or
              smap[k].startswith("athena_") for k in smap),
          f"off-pattern: {sorted(n for n in smap.values() if not n.startswith('athena_'))}")
    check("no duplicate names", len(declared) == len(set(declared)),
          "a tool is listed twice in plugin.yaml")

    cat = read(PLUGIN / "docs" / "catalog-entry.yaml")
    cap = cat[cat.index("provides_tools"):] if "provides_tools" in cat else ""
    cat_tools = [l.strip()[2:].strip().strip('"') for l in cap.splitlines()
                 if l.strip().startswith("- ")]
    check("the catalogue entry lists the same tools", set(cat_tools) == set(declared),
          f"only in catalogue: {sorted(set(cat_tools) - set(declared))}; "
          f"missing from catalogue: {sorted(set(declared) - set(cat_tools))}")


# ----------------------------------------------------------------------------- release files

def check_release_files() -> None:
    print("\nthe files a release is made of")
    lic = PLUGIN / "LICENSE"
    body = read(lic) if lic.is_file() else ""
    check("LICENSE exists and is MIT", "MIT" in body and "Permission is hereby granted" in body,
          f"{len(body)} bytes")

    notice = PLUGIN / "NOTICE"
    nb = read(notice) if notice.is_file() else ""
    check("NOTICE exists and names the vendored engine", "pinokiod" in nb and len(nb) > 200,
          f"{len(nb)} bytes")

    third = PLUGIN / "THIRD-PARTY.md"
    check("THIRD-PARTY.md exists", third.is_file() and third.stat().st_size > 1000,
          f"{third.stat().st_size if third.is_file() else 0} bytes")

    gi = PLUGIN / ".gitignore"
    gb = read(gi) if gi.is_file() else ""
    missing = [p for p in ("__pycache__", "settings.json", "cache/") if p not in gb]
    check(".gitignore keeps the machine's own files out", not missing,
          f"missing: {missing}")

    nm = PLUGIN / "engine" / "node_modules"
    check("the vendored engine's dependencies are present",
          nm.is_dir() and any(nm.iterdir()), str(nm))


# ----------------------------------------------------------------------------- third party

def walk_packages(nm: Path) -> Tuple[Dict[str, str], List[str], List[str]]:
    """(name@version -> licence, list in file order, package.json files left out).

    Every `package.json` under the tree, deduped on `name@version`, skipping the
    `example`/`fixture` directories — those hold a package.json that is a *file
    inside* a package rather than an installed dependency of ours, which is the
    distinction a licence inventory turns on.
    """
    found: Dict[str, str] = {}
    skipped: List[str] = []
    for root, dirs, files in os.walk(nm):
        dirs[:] = [d for d in dirs if d not in {".bin", ".cache"}]
        if "package.json" not in files:
            continue
        rel_parts = Path(root).relative_to(nm).parts
        if any(p in {"example", "examples", "fixture", "fixtures"} for p in rel_parts):
            skipped.append(str(Path(root).relative_to(nm)))
            continue
        try:
            pkg = json.loads(read(Path(root) / "package.json"))
        except (OSError, ValueError):
            continue
        name, ver = pkg.get("name"), pkg.get("version")
        if not name or not ver:
            continue
        lic = pkg.get("license")
        if not lic and isinstance(pkg.get("licenses"), list) and pkg["licenses"]:
            first = pkg["licenses"][0]
            lic = first.get("type") if isinstance(first, dict) else first
        found[f"{name}@{ver}"] = lic or "see package"
    return found, sorted(found, key=lambda k: (found[k], k)), skipped


def check_third_party() -> None:
    print("\nthe third-party inventory says what the tree says")
    if "--dump-third-party" in sys.argv:
        found, ordered, skipped = walk_packages(PLUGIN / "engine" / "node_modules")
        for k in ordered:
            print(f"- `{k}` — {found[k]}")
        print(f"\n{len(found)} packages, {len(skipped)} left out: {skipped}")
        return
    nm = PLUGIN / "engine" / "node_modules"
    third = PLUGIN / "THIRD-PARTY.md"
    if not nm.is_dir() or not third.is_file():
        check("the inventory can be checked at all", False, "engine/node_modules or THIRD-PARTY.md missing")
        return
    found, ordered, skipped = walk_packages(nm)
    text = read(third)

    m = re.search(r"^(\d+) packages,", text, re.M)
    check("the package count in the file is the walk's count",
          bool(m) and int(m.group(1)) == len(found),
          f"file says {m.group(1) if m else '?'}, walk found {len(found)}")

    # The table, in order: count descending, then the licence string as written.
    rows = re.findall(r"^\|\s*(.+?)\s*\|\s*(\d+)\s*\|\s*$", text, re.M)
    rows = [r for r in rows if r[0] != "Licence"]
    counted: Dict[str, int] = {}
    for k in ordered:
        counted[found[k]] = counted.get(found[k], 0) + 1
    want_rows = [[lic, str(n)] for lic, n in
                 sorted(counted.items(), key=lambda kv: (-kv[1], kv[0]))]
    check("the licence table is the walk's histogram, in the walk's order",
          [list(r) for r in rows] == want_rows,
          f"first difference at {next((i for i, (a, b) in enumerate(zip(rows, want_rows)) if list(a) != b), min(len(rows), len(want_rows)))}")

    # The full list: one line per package, in licence groups, names per group.
    #
    # Deliberately *not* an exact line-for-line comparison. Where one name appears at
    # several versions (`debug@2.6.9` beside `debug@4.4.3` and `debug@3.2.7`) the
    # committed file's order is not reconstructible from the tree — it follows neither
    # path depth, nor version, nor path string, which is what a sort over a
    # hash-ordered set looks like from outside. Demanding that order back would demand
    # a rule nobody can restate, and the check that matters is staleness: a package
    # added, removed or relicensed since the file was written.
    listed = [(m.group(1), m.group(2)) for m in re.finditer(r"^- `([^`]+)` — (.+?)\s*$", text, re.M)]
    want_list = [(k, found[k]) for k in ordered]

    def groups(pairs):
        out: Dict[str, List[str]] = {}
        for key, lic in pairs:
            out.setdefault(lic, []).append(key.rsplit("@", 1)[0])
        return {lic: sorted(names) for lic, names in out.items()}

    same_set = sorted(listed) == sorted(want_list)
    check("the full list holds exactly the packages the walk found",
          same_set,
          f"file has {len(listed)} lines, walk has {len(want_list)}; "
          f"only in file: {sorted(set(listed) - set(want_list))[:4]}; "
          f"missing from file: {sorted(set(want_list) - set(listed))[:4]}")

    g_file, g_walk = groups(listed), groups(want_list)
    check("the list is grouped by licence, and names are sorted inside each group",
          g_file == g_walk,
          f"licences differ: {sorted(set(g_file) ^ set(g_walk))[:4]}; "
          f"elsewhere: {[lic for lic in g_file if lic in g_walk and g_file[lic] != g_walk[lic]][:4]}")
    def group_order(pairs) -> List[str]:
        seen: List[str] = []
        for _, lic in pairs:
            if lic not in seen:
                seen.append(lic)
        return seen

    check("the licence groups run in licence order",
          group_order(listed) == group_order(want_list) == sorted(group_order(listed)),
          f"file: {group_order(listed)[:6]}")

    unlicensed = [k for k in ordered if found[k] == "see package"]
    check("the packages with no licence field are named in the file, and each is one",
          all(k in text for k in unlicensed),
          f"unnamed: {[k for k in unlicensed if k not in text]}")

    if skipped:
        check("the example/fixture package.json files are accounted for",
              str(len(skipped)) in text,
              f"walk left out {len(skipped)}: {skipped}")

    bad = sorted({found[k] for k in ordered
                  if any(c in found[k].upper() for c in COPYLEFT)})
    check("every licence in the tree is permissive (none of it is copyleft)",
          not bad, f"copyleft found: {bad}")

    # The engine's own version is named twice and both have to be the same engine.
    pkg = PLUGIN / "engine" / "node_modules" / "pinokiod" / "package.json"
    if pkg.is_file():
        v = json.loads(read(pkg)).get("version", "")
        check("THIRD-PARTY.md names the vendored engine's real version", bool(v) and v in text,
              f"pinokiod is {v!r}, which the file does not name")


# ----------------------------------------------------------------------------- manifest

def check_manifest() -> None:
    print("\nthe Hermes window this plugin claims")
    plug = read(PLUGIN / "plugin.yaml")
    spec = yaml_scalar(plug, "requires_hermes") or ""
    check("requires_hermes has a lower bound", ">" in spec, repr(spec))
    check("requires_hermes has an upper bound", "<" in spec,
          f"{spec!r} — an unbounded major version is how a working plugin stops importing")
    cat_spec = yaml_scalar(read(PLUGIN / "docs" / "catalog-entry.yaml"), "requires_hermes")
    check("the catalogue entry claims the same window", cat_spec == spec,
          f"catalogue={cat_spec!r} plugin={spec!r}")

    have = installed_hermes_version()
    if have is None:
        SKIPPED.append("hermes is not on PATH — the declared window was not tested against a running Hermes")
    else:
        check(f"the running Hermes ({have}) is inside the declared window",
              satisfies(have, spec), f"requires_hermes={spec!r}, running {have}")

    # Each requirement is quoted, so the quotes are the parse: splitting on commas
    # would cut `Pillow>=9,<14` in half and report a bound that is already there.
    deps_line = re.search(r"^python_dependencies:\s*(.+)$", plug, re.M)
    reqs = re.findall(r'"([^"]+)"', deps_line.group(1)) if deps_line else []
    unbounded = [r for r in reqs if "<" not in r]
    check("every python dependency is declared with a ceiling",
          bool(reqs) and not unbounded,
          f"{len(reqs)} declared; unbounded: {unbounded}")


# ----------------------------------------------------------------------------- paths and sizes

def shipped_files() -> List[Path]:
    out: List[Path] = []
    for root, dirs, files in os.walk(PLUGIN):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for f in files:
            p = Path(root) / f
            if p.suffix.lower() in SHIPPED_SUFFIXES:
                out.append(p)
    return out


def check_paths_and_sizes() -> None:
    print("\nno file names one machine, no file grows without saying so")
    author = re.compile(r"(?:[A-Za-z]:[\\/]Users[\\/][A-Za-z0-9_.-]+|/home/[A-Za-z0-9_.-]+/|/Users/[A-Za-z0-9_.-]+/)")
    hits = []
    for p in shipped_files():
        m = author.search(read(p))
        if m:
            hits.append(f"{p.relative_to(PLUGIN)}: {m.group(0)}")
    check("nothing in the plugin hard-codes somebody's home directory", not hits,
          "; ".join(hits[:4]))

    over = []
    for p in shipped_files():
        cap = SIZE_CAPS.get(str(p.relative_to(PLUGIN)).replace("\\", "/"), ANY_FILE_CAP)
        n = len(read(p).splitlines())
        if n > cap:
            over.append(f"{p.relative_to(PLUGIN)} {n} > {cap}")
    check("no shipped file is over its cap", not over, "; ".join(over))


def main() -> int:
    print(f"plugin: {PLUGIN}")
    if "--dump-third-party" in sys.argv:
        check_third_party()
        return 0
    check_versions()
    check_tools()
    check_release_files()
    check_third_party()
    check_manifest()
    check_paths_and_sizes()
    print(f"\n{PASS}/{PASS + FAIL} checks passed")
    for s in SKIPPED:
        print(f"note: {s}")
    if FAILURES:
        print("failing: " + "; ".join(FAILURES[:12]))
    return 1 if FAIL else 0


if __name__ == "__main__":
    sys.exit(main())
